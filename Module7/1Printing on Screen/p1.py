# 1.	Write a Python program to print a formatted string using print() and f-string. 

# Define variables
Name = "Kajal"
Age = 23
City = "Surat"

# Print a formatted string using an f-string
print(f"""My name is {Name}. 
i am {Age} old.
i live at {City}.""")

# Output: 
# My name is Kajal. 
# i am 23 old.        
# i live at Surat. 